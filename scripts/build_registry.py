"""Rebuild results/registry.csv and EXPERIMENTS.md from experiments/*/ (config.json + metrics.json + val logits).
Val only. Every finished run with val logits gets a row; the Baseline-0 rows and the frozen/holdout columns come from
results/registry_manual.csv (hand-maintained: run_id, frozen, holdout_auc, note).
Usage: python scripts/build_registry.py"""
import json
import os
import sys
import time

import numpy as np
import pandas as pd

W = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(W, "scripts"))
os.chdir(W)
import leaderboard_now as lb  # noqa: E402

ENS = ["mae_vitb_p3_42_in1kmae_e800_ft", "mae_vitb_p3_42_in1kmae_e400_ft", "mae_in1kB_e400_s1_ft",
       "mae_in1kB_e800_s1_ft", "mimv2b_llrd75"]


def init_of(r, m):
    ck = m.get("init_ckpt")
    if ck:
        enc = os.path.basename(os.path.dirname(ck))
        return f"{m.get('arch', '?')} → {enc}"
    return f"{m.get('arch', '?')} ({'pretrained' if m.get('pretrained') else 'scratch'})"


def final_block():
    """'Current best' lines for the final frozen k-fold ensembles: OOF val over all 170k train+val rows (each row scored by
    the fold model that did not train on it; mean over recipes of the TTA8 logits) and the one holdout evaluation."""
    from kfold_ens import oof
    out = []
    for name, recipes, label in (("final_kfold_plain", ["vit_plain", "cnn400_plain"], "FINAL CLASSIFIER"),
                                 ("final_kfold_robust", ["vit_rob", "cnn400_rob"], "Robust alternative")):
        z = np.mean([oof(r, len(lb.y)) for r in recipes], 0)
        m = np.isfinite(z)
        t, dd = lb.y[m].astype(float), lb.k.pipeline.values[m] == "D2"
        v = lb.row(name, z[m], "-", t, dd)
        hp = f"experiments/holdout_evals/{name}.json"
        h = json.load(open(hp))["holdout"] if os.path.exists(hp) else {}
        hs = (f"holdout loss {h['logloss']:.4f}, AUC {h['auc']:.5f}, SIMCT AUC {h['per_pipeline']['D2']:.5f}, "
              f"TPR@1e-3 SLSim {h['per_pipeline_tpr@1e-3']['D1']:.3f} / SIMCT {h['per_pipeline_tpr@1e-3']['D2']:.3f}"
              if h else "not holdout-evaluated")
        out.append(f"- **{label}: {name}** (10-fold {' + '.join(recipes)}, {10 * len(recipes)} models, TTA8 logit mean): "
                   f"OOF val ({int(m.sum())} rows) loss {v['loss']}, AUC {v['AUC']}, SIMCT AUC {v['AUC_SIMCT']}, "
                   f"TPR@1e-3 SIMCT {v['TPR3_SIMCT']}; {hs}.")
    return out


def main():
    man = pd.read_csv("results/registry_manual.csv") if os.path.exists("results/registry_manual.csv") else \
        pd.DataFrame(columns=["run_id", "frozen", "date", "val_loss", "val_auc", "holdout_auc", "note"])
    man = man.set_index("run_id")
    rows = []
    for r in sorted(os.listdir("experiments")):
        d = os.path.join("experiments", r)
        try:
            z = lb.logits(r)
            cfg = json.load(open(os.path.join(d, "config.json")))
        except (FileNotFoundError, NotADirectoryError, json.JSONDecodeError):
            continue
        if len(z) != len(lb.yv) or not np.isfinite(z).all():
            continue
        met = {}
        if os.path.exists(os.path.join(d, "metrics.json")):
            met = json.load(open(os.path.join(d, "metrics.json")))
        m, t = cfg.get("model", {}), cfg.get("train", {})
        row = lb.row(r, z, lb.params(r), *lb.labels(r))                 # k-fold runs: their own fold rows
        row["val_set"] = lb.val_set(r)
        row.update(date=time.strftime("%Y-%m-%d", time.localtime(os.path.getmtime(d))),
                   track=cfg.get("track", ""), init=init_of(r, m),
                   res_patch=f"{m.get('size', m.get('img_size', '?'))}/p{m.get('patch_size', '-')}",
                   norm=f"{m.get('norm', '?')}{'' if m.get('norm_a') is None else m.get('norm_a')}",
                   seed=cfg.get("seed", 0), gpu_h=round(met.get("gpu_hours", float("nan")), 1),
                   frozen=man["frozen"].get(r, "no") if len(man) else "no",
                   holdout_auc=man["holdout_auc"].get(r, "") if len(man) else "")
        rows.append(row)
    df = pd.DataFrame(rows).sort_values("loss_TS")
    cols = ["model", "date", "track", "init", "res_patch", "norm", "seed", "val_set", "params_M", "gpu_h", "loss", "loss_TS",
            "AUC", "AUC_SIMCT", "TPR3_all", "TPR3_SLSim", "TPR3_SIMCT", "frozen", "holdout_auc"]
    df = df[cols].rename(columns={"model": "run_id"})
    df.to_csv("results/registry.csv", index=False)

    fz = man[man["frozen"].astype(str).str.lower() == "yes"] if len(man) else man
    ens = lb.row("ENSEMBLE best5 (" + " + ".join(ENS) + ")", np.mean([lb.logits(r) for r in ENS], 0), "-")
    top = df[df.val_set == "val"].iloc[0]                              # single models on the standard val split
    fin = final_block()
    L = ["# EXPERIMENTS", "",
         f"_Generated by `scripts/build_registry.py` on {time.strftime('%Y-%m-%d %H:%M')} from experiments/*/ "
         "(mirror: results/registry.csv). Val metrics on snapshot-ensemble TTA8 logits where available, else TTA8. "
         "loss_TS = cross-fit temperature-scaled loss. TPR3 = TPR at FPR 1e-3._", "",
         "## Current best", "",
         ] + fin + [
         f"- **Earlier ensemble (standard val):** {ens['model']}: loss {ens['loss']}, TS {ens['loss_TS']}, AUC {ens['AUC']}, "
         f"SIMCT AUC {ens['AUC_SIMCT']}, TPR@1e-3 SLSim {ens['TPR3_SLSim']} / SIMCT {ens['TPR3_SIMCT']}.",
         f"- **Single model (val, by TS loss):** {top['run_id']}: loss {top['loss']}, TS {top['loss_TS']}, "
         f"AUC {top['AUC']}, SIMCT AUC {top['AUC_SIMCT']}, TPR@1e-3 SIMCT {top['TPR3_SIMCT']}. "
         "Fair recipe mean over FT seeds ≈ 0.0222.",
         "- **Floor:** Baseline 0 MLP on hand-crafted features: AUC 0.9838 (SLSim 0.996, SIMCT 0.963).",
         f"- **Frozen models:** {len(fz)} (table below). **Holdout:** see experiments/holdout_evals/ and "
         "logs/holdout_evals.log.", "",
         "## Frozen models (read by scripts/eval_holdout.py; source: results/registry_manual.csv)", "",
         "| ID | frozen? | date frozen | val loss (best.pt TTA8) | val AUC | holdout AUC | note |",
         "|---|---|---|---|---|---|---|"] + [
         f"| {r} | yes | {fz.loc[r, 'date']} | {fz.loc[r, 'val_loss']} | {fz.loc[r, 'val_auc']} | "
         f"{fz.loc[r, 'holdout_auc'] if str(fz.loc[r, 'holdout_auc']) != 'nan' else ''} | {fz.loc[r, 'note']} |"
         for r in fz.index] + ["",
         "## Baseline 0 (CPU, hand-crafted features)", "",
         "| run | model | val loss | val AUC | TPR@1e-2 |", "|---|---|---|---|---|",
         "| b0_lr_nopipe | logistic regression, 54 features | 0.388 | 0.9077 | 0.183 |",
         "| b0_mlp_nopipe | MLP 256-256, 54 features | 0.156 | 0.9838 | 0.640 |",
         "| b0_gbm_nopipe | LightGBM, 54 features | 0.165 | 0.9812 | 0.584 |",
         "| b0_gbm_pipe (diagnostic) | LightGBM + pipeline flag | 0.148 | 0.9843 | 0.634 |", "",
         f"## All deep runs with val logits ({len(df)}), sorted by TS loss", "",
         "| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    for _, r_ in df.iterrows():
        L.append("| " + " | ".join(str(v) for v in r_.values) + " |")
    open("EXPERIMENTS.md", "w").write("\n".join(L) + "\n")
    print(f"{len(df)} runs; best TS {top['run_id']} {top['loss_TS']}; ensemble TS {ens['loss_TS']}")


if __name__ == "__main__":
    main()
